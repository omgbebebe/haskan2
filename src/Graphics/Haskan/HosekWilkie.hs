bernstein5 :: Float -> Float -> Float -> Float -> Float -> Float -> Float -> Float
bernstein5 a0 a1 a2 a3 a4 a5 se =
  let o = 1.0 - se
  in  o*o*o*o*o * a0
    + 5.0 * o*o*o*o * se * a1
    + 10.0 * o*o*o * se*se * a2
    + 10.0 * o*o * se*se*se * a3
    + 5.0 * o * se*se*se*se * a4
    + se*se*se*se*se * a5

clampV :: Float -> Float -> Float -> Float
clampV lo hi x = max lo (min hi x)

dotV3 :: V3 Float -> V3 Float -> Float
dotV3 (V3 ax ay az) (V3 bx by bz) = ax * bx + ay * by + az * bz

cookChannel :: [Float] -> Float -> Float -> Float -> [Float]
cookChannel dataset turbidity albedo solarElevation =
  let intTurb = max 1 (min 10 (truncate turbidity :: Int))
      turbRem = turbidity - fromIntegral intTurb
      se = max 0.0 (min 1.0 ((solarElevation / (pi / 2.0)) ** (1.0 / 3.0)))
      elevSample :: Int -> Int -> Float
      elevSample base ki = dataset !! (base + ki * 9)
      cookCoeff :: Int -> Float
      cookCoeff i =
        let a0low = 54 * (intTurb - 1)
            a1low = 540 + 54 * (intTurb - 1)
            val = (1.0 - albedo) * (1.0 - turbRem)
                    * bernstein5 (elevSample a0low i) (elevSample (a0low+9) i) (elevSample (a0low+18) i) (elevSample (a0low+27) i) (elevSample (a0low+36) i) (elevSample (a0low+45) i) se
                + albedo * (1.0 - turbRem)
                    * bernstein5 (elevSample a1low i) (elevSample (a1low+9) i) (elevSample (a1low+18) i) (elevSample (a1low+27) i) (elevSample (a1low+36) i) (elevSample (a1low+45) i) se
        in if intTurb >= 10
           then val
           else let a0high = 54 * intTurb
                    a1high = 540 + 54 * intTurb
                in val
                   + (1.0 - albedo) * turbRem
                       * bernstein5 (elevSample a0high i) (elevSample (a0high+9) i) (elevSample (a0high+18) i) (elevSample (a0high+27) i) (elevSample (a0high+36) i) (elevSample (a0high+45) i) se
                   + albedo * turbRem
                       * bernstein5 (elevSample a1high i) (elevSample (a1high+9) i) (elevSample (a1high+18) i) (elevSample (a1high+27) i) (elevSample (a1high+36) i) (elevSample (a1high+45) i) se
  in map cookCoeff [0..8]

