hwSkyRadiance :: HWCoeffs -> V3 Float -> V3 Float -> V3 Float
hwSkyRadiance coeffs viewDir sunDir =
  let V3 ar ag ab = hwA coeffs
      V3 br bg bb = hwB coeffs
      V3 cr cg cb = hwC coeffs
      V3 dr dg db = hwD coeffs
      V3 er eg eb = hwE coeffs
      V3 fr fg fb = hwF coeffs
      V3 gr gg gb = hwG coeffs
      V3 hr hg hb = hwH coeffs
      V3 ir ig ib = hwI coeffs

      cosTheta = max 1e-4 (viewDir ^. _y)
      cosGamma = clampV (-1) 1 (dotV3 viewDir sunDir)
      gammaSq = cosGamma * cosGamma
      sqrtCosTheta = sqrt cosTheta

      f1R = 1.0 + ar * exp (br / (cosTheta + 0.01))
      f1G = 1.0 + ag * exp (bg / (cosTheta + 0.01))
      f1B = 1.0 + ab * exp (bb / (cosTheta + 0.01))

      chiR = (1.0 + gammaSq) / ((1.0 + ir*ir - 2.0*ir*cosGamma) ** 1.5)
      chiG = (1.0 + gammaSq) / ((1.0 + ig*ig - 2.0*ig*cosGamma) ** 1.5)
      chiB = (1.0 + gammaSq) / ((1.0 + ib*ib - 2.0*ib*cosGamma) ** 1.5)

      f2R = cr + dr * exp (er * cosGamma) + fr * gammaSq + gr * chiR + hr * sqrtCosTheta
      f2G = cg + dg * exp (eg * cosGamma) + fg * gammaSq + gg * chiG + hg * sqrtCosTheta
      f2B = cb + db * exp (eb * cosGamma) + fb * gammaSq + gb * chiB + hb * sqrtCosTheta

      radR = f1R * f2R
      radG = f1G * f2G
      radB = f1B * f2B
   in V3 (max 0 radR) (max 0 radG) (max 0 radB)
